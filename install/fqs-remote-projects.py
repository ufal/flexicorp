#!/usr/bin/env python3
"""Search-only TEITOK projects for the corpora of an FQS: one small project per corpus, so a TEITOK
installation can search them through that FQS (flexicorp) before anything else is connected to it,
e.g. a new FQS server reached through an SSH tunnel:

    ssh -N -L 18787:127.0.0.1:8787 USER@FQS-MACHINE
    python3 flexicorp/install/fqs-remote-projects.py --teitok /var/www/html/teitok --fqs http://127.0.0.1:18787 \
        --group test-kontext-dummies [--secret-file FILE] [--only ID,ID] [--dry-run] [--remove]

The projects go into one folder, `<teitok>/<group>/<corpus id>/` (index.php, Resources/settings.xml
with `<flexicorp fqs_url="…" fqs_corpus_id="…" [fqs_secret="…"]/>`, a home page, tmp/), so a whole set
is removed at once (--remove). No corpus data: flexicorp finds the corpus in FQS's catalogue over HTTP
and searches it there (fc_fqs_catalog.php). Open <teitok URL>/<group>/<corpus id>/index.php?action=flexicorp.

--fqs is the FQS URL as the web server reaches it. --secret-file: a file with FQS_SECRET=… (that
FQS's secret), written into the projects' settings so flexicorp signs its requests with the logged-in
role instead of visitor; keep such a group out of any repository. The group folder carries a
.fqs-remote marker: reruns update it, --remove deletes it, folders without the marker are left alone.
"""
import argparse
import base64
import hashlib
import hmac
import json
import os
import re
import shutil
import sys
import time
import urllib.parse
import urllib.request
from xml.sax.saxutils import escape, quoteattr

MARKER = ".fqs-remote"
INDEX_PHP = """<?php
	// define where the TEITOK common files can be found
	$ttroot = getenv('TT_ROOT') or "..";
	date_default_timezone_set('UTC');
	ini_set('display_errors', '1');
	error_reporting(E_ERROR|E_WARNING);
	include ( "$ttroot/common/Sources/main.php" );
?>
"""


def read_secret(path):
    for line in open(os.path.expanduser(path), encoding="utf-8"):
        if line.startswith("FQS_SECRET="):
            return line.split("=", 1)[1].strip().strip("\"'")
    sys.exit(f"no FQS_SECRET= line in {path}")


def admin_token(secret):
    b64 = lambda b: base64.urlsafe_b64encode(b).rstrip(b"=").decode()
    now = int(time.time())
    head = b64(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
    body = b64(json.dumps({"iss": "teitok-flexicorp", "sub": "catalog", "role": "admin", "iat": now, "exp": now + 120}).encode())
    sig = b64(hmac.new(secret.encode(), f"{head}.{body}".encode(), hashlib.sha256).digest())
    return f"{head}.{body}.{sig}"


def corpora(url, secret):
    req = urllib.request.Request(url.rstrip("/") + "/corpora?request_role=admin&include_noncurrent=true",
                                 headers={"Accept": "application/json", **({"Authorization": "Bearer " + admin_token(secret)} if secret else {})})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.loads(r.read()).get("corpora") or []


def safe(s):
    return re.sub(r"[^A-Za-z0-9_-]+", "_", s).strip("_")


def settings_xml(row, folder, url, name, secret):
    cid, label = row["id"], row.get("label") or row["id"]
    sec = f" fqs_secret={quoteattr(secret)}" if secret else ""
    return f"""<?xml version="1.0"?>
<ttsettings>
	<!-- Generated by dev/ops/fqs-remote-projects.py: a search-only view of corpus {escape(cid)} on the FQS
	     at {escape(url)} ({escape(name)}). No local data. Regenerate rather than edit. -->
	<languages prefixed="0" default="en">
		<options><item key="en" locale="en_UK.UTF-8" menu="EN" name="English"/></options>
	</languages>
	<menu>
		<itemlist noshare="1">
			<item key="home" display="Home"/>
			<item key="flexicorp" display="Search"/>
		</itemlist>
	</menu>
	<defaults>
		<title display={quoteattr(label)}>{escape(label)} (via FQS {escape(name)})</title>
		<base foldername={quoteattr(folder)}/>
	</defaults>
	<flexicorp fqs_url={quoteattr(url)} fqs_corpus_id={quoteattr(cid)}{sec}/>
</ttsettings>
"""


def home_html(row, url, name):
    eng = row.get("preferred_backend") or "?"
    size = row.get("corpus_size")
    return (f"<p><b>{escape(row.get('label') or row['id'])}</b>: a search-only view of corpus <code>{escape(row['id'])}</code> "
            f"on the FQS <i>{escape(name)}</i> ({escape(url)}), engine {escape(str(eng))}"
            + (f", {int(size):,} tokens" if str(size or '').isdigit() else "") + ".</p>\n"
            "<p><a href=\"index.php?action=flexicorp\">Search it</a>. Nothing of the corpus is stored here.</p>\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--teitok", required=True, help="the folder TEITOK projects live in (beside the shared project)")
    ap.add_argument("--fqs", help="FQS URL as the local web server reaches it (e.g. the tunnel)")
    ap.add_argument("--group", required=True, help="folder for this set of projects, e.g. test-kontext-dummies")
    ap.add_argument("--name", help="how the pages name this FQS (default: the group)")
    ap.add_argument("--secret-file", help="file with FQS_SECRET=… (that FQS's secret)")
    ap.add_argument("--only", help="comma-separated corpus ids")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--remove", action="store_true", help="delete this group folder")
    a = ap.parse_args()
    group = safe(a.group)
    gdir = os.path.join(os.path.expanduser(a.teitok), group)
    marked = os.path.isfile(os.path.join(gdir, MARKER))
    if os.path.isdir(gdir) and not marked:
        sys.exit(f"{gdir} exists and was not made by this script: choose another --group")

    if a.remove:
        if not marked:
            sys.exit(f"nothing to remove: {gdir}")
        print(("would remove " if a.dry_run else "removed ") + gdir)
        if not a.dry_run:
            shutil.rmtree(gdir)
        return
    if not a.fqs:
        sys.exit("--fqs is needed (except with --remove)")

    secret = read_secret(a.secret_file) if a.secret_file else ""
    name = a.name or a.group
    rows = corpora(a.fqs, secret)
    only = {x.strip() for x in a.only.split(",")} if a.only else None
    made = 0
    if not a.dry_run:
        os.makedirs(gdir, exist_ok=True)
        with open(os.path.join(gdir, MARKER), "w", encoding="utf-8") as f:
            f.write(json.dumps({"fqs": a.fqs, "generated": time.strftime("%Y-%m-%d %H:%M")}) + "\n")
    for row in rows:
        cid = row.get("id", "")
        if not cid or (only and cid not in only):
            continue
        if str(row.get("preferred_backend", "")).lower() == "manatee":
            print(f"skipped {cid}: a Manatee corpus (KonText runs it, FQS does not)")
            continue
        folder = safe(cid)
        p = os.path.join(gdir, folder)
        print(f"{'would write' if a.dry_run else 'wrote'} {group}/{folder}  ({row.get('preferred_backend')}, {row.get('label')})")
        if a.dry_run:
            continue
        for sub in ("Resources", "Pages", "tmp"):
            os.makedirs(os.path.join(p, sub), exist_ok=True)
        os.chmod(os.path.join(p, "tmp"), 0o777)
        with open(os.path.join(p, "index.php"), "w", encoding="utf-8") as f:
            f.write(INDEX_PHP)
        with open(os.path.join(p, "Resources", "settings.xml"), "w", encoding="utf-8") as f:
            f.write(settings_xml(row, folder, a.fqs, name, secret))
        with open(os.path.join(p, "Pages", "home.html"), "w", encoding="utf-8") as f:
            f.write(home_html(row, a.fqs, name))
        made += 1
    print(f"{made} projects in {gdir}; open <teitok URL>/{group}/<corpus id>/index.php?action=flexicorp")


if __name__ == "__main__":
    main()
